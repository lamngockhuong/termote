#!/bin/sh
# Prints the Homebrew formula (Formula/termote.rb in lamngockhuong/homebrew-tap)
# for a stable release, taking each archive's hash from the release's
# checksums.txt. The release workflow verifies that file's signature first.
# Usage: scripts/homebrew-formula.sh <X.Y.Z> <checksums.txt>
set -eu

die() {
    echo "homebrew-formula: $*" >&2
    exit 1
}

[ $# -eq 2 ] || die "usage: homebrew-formula.sh <X.Y.Z> <checksums.txt>"
VERSION=$1
CHECKSUMS=$2

# A case, not grep: grep matches line by line and would pass "1.2.3<newline>x".
case $VERSION in
'' | *[!0-9.]* | .* | *. | *..*) die "version must be X.Y.Z (no pre-release): $VERSION" ;;
esac
[ "$(printf '%s' "$VERSION" | tr -cd . | wc -c)" -eq 2 ] || die "version must be X.Y.Z (no pre-release): $VERSION"
[ -f "$CHECKSUMS" ] && [ -r "$CHECKSUMS" ] || die "cannot read $CHECKSUMS"

BASE="https://github.com/lamngockhuong/termote/releases/download/v$VERSION"

# archive_hash prints the sha256 checksums.txt holds for termote-<v>-<os>-<arch>.tar.gz.
archive_hash() {
    archive="termote-$VERSION-$1.tar.gz"
    h=$(awk -v f="$archive" '$2 == f || $2 == "*" f { print $1; exit }' "$CHECKSUMS")
    echo "$h" | grep -Eq '^[0-9a-f]{64}$' || die "no valid sha256 for $archive in $CHECKSUMS"
    echo "$h"
}

DARWIN_ARM64=$(archive_hash darwin-arm64)
DARWIN_AMD64=$(archive_hash darwin-amd64)
LINUX_ARM64=$(archive_hash linux-arm64)
LINUX_AMD64=$(archive_hash linux-amd64)

cat <<EOF
# Generated by scripts/homebrew-formula.sh in lamngockhuong/termote; do not edit by hand.
class Termote < Formula
  desc "Self-hosted PWA to control Claude Code or any terminal from phone or desktop"
  homepage "https://termote.ohnice.app"
  license "MIT"

  on_macos do
    on_arm do
      url "$BASE/termote-$VERSION-darwin-arm64.tar.gz"
      sha256 "$DARWIN_ARM64"
    end
    on_intel do
      url "$BASE/termote-$VERSION-darwin-amd64.tar.gz"
      sha256 "$DARWIN_AMD64"
    end
  end

  on_linux do
    on_arm do
      url "$BASE/termote-$VERSION-linux-arm64.tar.gz"
      sha256 "$LINUX_ARM64"
    end
    on_intel do
      url "$BASE/termote-$VERSION-linux-amd64.tar.gz"
      sha256 "$LINUX_AMD64"
    end
  end

  def install
    bin.install "bin/termote"
  end

  def caveats
    <<~EOS
      Termote needs a terminal backend: brew install tmux (or Herdr, or Zellij with --mux zellij).
      Start the server and register it to run at login:
        termote start
      Upgrade:   brew upgrade termote && termote restart
      Uninstall: termote uninstall && brew uninstall termote
    EOS
  end

  test do
    assert_equal "Termote v#{version}", shell_output("#{bin}/termote version").strip
  end
end
EOF
