// The agent has a logo here
export const hasAgentLogo = (agent?: string) =>
  !!agent && Object.hasOwn(LOGOS, agent)

// An agent's logo at the size of the text around it (1em), hidden from
// screen readers: the tab's name is next to it. Gradient ids carry useId
// (only its letters and digits, to stay a plain url(#id)), as the same logo
// shows in several places at once.
export function AgentLogo({
  agent,
  className = '',
}: {
  agent: string
  className?: string
}) {
  const uid = `agent-logo-${useId().replace(/[^\w-]/g, '')}`
  const draw = Object.hasOwn(LOGOS, agent) ? LOGOS[agent] : undefined
  if (!draw) return null
  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
      data-agent-logo={agent}
      className={`inline-block size-[1em] shrink-0 ${className}`}
    >
      {draw(uid)}
    </svg>
  )
}
